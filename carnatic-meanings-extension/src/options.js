const $ = (id) => document.getElementById(id);
const status = (t) => { $("status").textContent = t; setTimeout(() => ($("status").textContent = ""), 2500); };

chrome.storage.local.get(["apiKey", "model"]).then(({ apiKey, model }) => {
  $("apiKey").value = apiKey || "";
  $("model").value = model || "";
});

$("save").addEventListener("click", async () => {
  const apiKey = $("apiKey").value.trim();
  const model = $("model").value.trim();
  await chrome.storage.local.set({ apiKey });
  if (model) await chrome.storage.local.set({ model });
  else await chrome.storage.local.remove("model");
  status("Saved.");
});

$("clearSongs").addEventListener("click", async () => {
  if (!confirm("Delete all songs generated by Claude or imported from files? Timings are kept.")) return;
  await chrome.storage.local.remove("customSongs");
  status("Deleted.");
});
